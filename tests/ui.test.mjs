import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import Handlebars from 'handlebars';
import {fixture} from '../tools/ui-fixture.mjs';

test('Foundry bootstrap and template render both calendars, GM controls and safe player notes', async () => {
  const f = await fixture();
  const source = await readFile(new URL('../templates/calendar.hbs', import.meta.url), 'utf8');
  const template = Handlebars.compile(source);
  let html = template(await f.app._prepareContext());
  assert.equal((html.match(/data-day=/g) ?? []).length, 240);
  assert.ok(html.includes('Segredo da Mestra'));
  assert.ok(html.includes('data-date-form'));
  f.app.newDraft();
  f.app.draft.description='<script>alert(1)</script>';
  const editor=template(await f.app._prepareContext());
  assert.ok(editor.includes('data-record-form'));
  assert.ok(editor.includes('&lt;script&gt;'));
  f.app.tab='calendar';
  assert.ok(!html.includes('<script>alert'));
  const sourcePage=f.game.journal.get(f.values.get('diaryBooks').gm).pages[0];
  let archiveClick,confirmations=0;
  const archiveButton={dataset:{archive:sourcePage.uuid},addEventListener:(type,fn)=>{archiveClick=fn;}};
  f.app.element={querySelector:()=>null,querySelectorAll:selector=>selector==='[data-archive]'?[archiveButton]:[]};
  foundry.applications.api.DialogV2.confirm=async()=>++confirmations===1;
  f.app._onRender(await f.app._prepareContext(),{});
  await archiveClick();
  assert.equal(confirmations,2);
  assert.equal(sourcePage.flags['opath-calendar'].record.archived,false);
  confirmations=0;foundry.applications.api.DialogV2.confirm=async()=>{confirmations++;return true;};
  await archiveClick();
  assert.equal(confirmations,2);
  assert.equal(sourcePage.flags['opath-calendar'].record.archived,true);
  // Restore before checking the public/player calendar.
  await sourcePage.update({'flags.opath-calendar.record.archived':false});
  await CONFIG.queries['opath-calendar.syncRecord']({pageUuid:sourcePage.uuid});
  f.app.element=null;
  const before = f.game.time.worldTime;
  await f.game.settings.set('opath-calendar','mode','solar');
  html = template(await f.app._prepareContext());
  assert.equal((html.match(/data-day=/g) ?? []).length, 480);
  assert.ok(html.includes('volta 2/2'));
  assert.equal(f.game.time.worldTime, before);
  f.game.user=f.game.users.get('alice');
  html = template(await f.app._prepareContext());
  assert.ok(!html.includes('Segredo da Mestra'));
  assert.ok(html.includes('Viagem da guilda'));
  assert.ok(!html.includes('data-date-form'));
  assert.ok(!html.includes('data-advance='));
  assert.ok(!html.includes('name="branch"'));
  assert.ok(!html.includes('Definir como dia atual'));
  f.app.newDraft();
  html=template(await f.app._prepareContext());
  assert.ok(html.includes('data-record-form'));
  assert.ok(html.includes('Jogadores escolhidos'));
  assert.ok(html.includes('data-action-local="calendar"'));
  assert.equal(f.listeners.get('preDeleteJournalEntry')(f.game.journal.get(f.values.get('diaryBooks').alice)),false);
  let notices=[];ui.notifications.info=message=>notices.push(message);
  const worldHook=f.listeners.get('updateWorldTime');
  f.game.user=f.game.users.get('gm');
  f.game.time.worldTime+=86400;worldHook();worldHook();
  assert.equal(notices.filter(n=>n.includes('Feriado')).length,1);
  f.game.user=f.game.users.get('alice');f.game.time.worldTime+=240*86400;worldHook();
  assert.equal(notices.filter(n=>n.includes('Feriado')).length,1);
  f.app.newDraft();await f.app._prepareContext();
  const nativeFormData=globalThis.FormData;
  try{
    const values={title:'Rascunho durante o relógio',description:'Texto digitado e ainda não salvo',location:'Alberich',weather:'Chuva',image:'',visibility:'private',repeat:'once'};
    globalThis.FormData=class{get(name){return values[name];}getAll(){return [];}};
    f.app.element={querySelector:selector=>selector==='[data-record-form]'?{}:null};
    f.game.time.worldTime+=3600;const refreshed=await f.app._prepareContext();
    assert.equal(refreshed.draft.description,values.description);
    assert.equal(refreshed.draft.title,values.title);
  }finally{globalThis.FormData=nativeFormData;f.app.element=null;}
});

test('manifest only ships existing runtime files and requires SmallTime', async () => {
  const manifest = JSON.parse(await readFile(new URL('../module.json', import.meta.url), 'utf8'));
  assert.deepEqual(manifest.relationships.requires.map(r => r.id), ['smalltime']);
  for (const file of [...manifest.esmodules, ...manifest.styles, 'templates/calendar.hbs']) await readFile(new URL(`../${file}`, import.meta.url));
});
